create policy "users can read own profile" on public.users for select to authenticated using (id = (select auth.uid()));
create policy "users can read own company memberships" on public.company_users for select to authenticated using (user_id = (select auth.uid()));

create policy "organization members can read organization" on public.organizations for select to authenticated using (
  id in (select organization_id from public.users where id = (select auth.uid()))
);

create policy "authorized users can read companies" on public.companies for select to authenticated using (
  organization_id in (select organization_id from public.users where id = (select auth.uid()) and role in ('super_admin', 'agency_admin'))
  or id in (select company_id from public.company_users where user_id = (select auth.uid()))
);

create policy "authorized users can read services" on public.services for select to authenticated using (
  company_id in (select id from public.companies)
);
create policy "authorized users can read campaigns" on public.campaigns for select to authenticated using (
  company_id in (select id from public.companies)
);
create policy "authorized users can read ad groups" on public.ad_groups for select to authenticated using (
  campaign_id in (select id from public.campaigns)
);
create policy "authorized users can read ads" on public.ads for select to authenticated using (
  ad_group_id in (select id from public.ad_groups)
);
create policy "authorized users can read creative metadata" on public.creative_metadata for select to authenticated using (
  ad_id in (select id from public.ads)
);
create policy "organization users can read channels" on public.marketing_channels for select to authenticated using (
  organization_id in (select organization_id from public.users where id = (select auth.uid()))
);
create policy "authorized users can read marketing metrics" on public.daily_marketing_metrics for select to authenticated using (company_id in (select id from public.companies));
create policy "authorized users can read website metrics" on public.website_metrics for select to authenticated using (company_id in (select id from public.companies));
create policy "authorized users can read seo metrics" on public.seo_metrics for select to authenticated using (company_id in (select id from public.companies));
create policy "authorized users can read gbp metrics" on public.gbp_metrics for select to authenticated using (company_id in (select id from public.companies));
create policy "authorized users can read leads" on public.leads for select to authenticated using (company_id in (select id from public.companies));
create policy "authorized users can read lead events" on public.lead_events for select to authenticated using (lead_id in (select id from public.leads));
create policy "authorized users can read appointments" on public.appointments for select to authenticated using (lead_id in (select id from public.leads));
create policy "authorized users can read quotes" on public.quotes for select to authenticated using (lead_id in (select id from public.leads));
create policy "authorized users can read projects" on public.projects for select to authenticated using (lead_id in (select id from public.leads));
create policy "authorized users can read attribution" on public.revenue_attribution for select to authenticated using (company_id in (select id from public.companies));
create policy "admins can read reporting integrations" on public.reporting_integration_connections for select to authenticated using (
  company_id in (select id from public.companies)
  and exists (select 1 from public.users where id = (select auth.uid()) and role in ('super_admin', 'agency_admin', 'company_admin'))
);
create policy "admins can read sync logs" on public.sync_logs for select to authenticated using (
  integration_connection_id in (select id from public.reporting_integration_connections)
);

revoke all on public.reporting_integration_connections from anon;
revoke all on public.sync_logs from anon;
